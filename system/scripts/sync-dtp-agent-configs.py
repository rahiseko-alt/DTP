#!/usr/bin/env python3
"""Generate Claude official-format agents/skills from the Codex source definitions."""
import argparse
import json
from pathlib import Path
import sys
import tomllib


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    root=Path(__file__).resolve().parents[2]
    config=tomllib.loads((root/'.codex/config.toml').read_text(encoding='utf-8'))
    outputs={}
    for role,entry in config['agents'].items():
        if not isinstance(entry,dict):continue
        instructions=tomllib.loads((root/'.codex'/entry['config_file']).read_text(encoding='utf-8'))['developer_instructions']
        name=role.replace('_','-')
        meta=['---','name: '+name,'description: '+json.dumps(entry['description'],ensure_ascii=False),'model: inherit']
        if role in {'dtp_reviewer','dtp_chief'}:
            meta.append('tools: [Read, Grep, Glob]')
            instructions+='\nClaudeのこの役割は閲覧ツールのみ。コマンドで取得するPDFハッシュ・ページ数・検証ログは統合担当に取得させ、現物と照合する。取得できない検査は未確認と返す。\n'
        outputs[root/'.claude/agents'/f'{name}.md']='\n'.join(meta)+ '\n---\n\n<!-- Generated by system/scripts/sync-dtp-agent-configs.py. Edit source role TOML. -->\n\n'+instructions
    for source in (root/'.agents/skills').glob('dtp-*/*'):
        if source.is_file():outputs[root/'.claude/skills'/source.parent.name/source.name]=source.read_text(encoding='utf-8')
    failures=[]
    for path,text in outputs.items():
        if a.check:
            if not path.exists() or path.read_text(encoding='utf-8')!=text:failures.append(path.relative_to(root).as_posix())
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8')
    if failures:
        print('CONFIG_DRIFT: '+', '.join(failures),file=sys.stderr);return 1
    print(('CHECKED' if a.check else 'GENERATED')+f': {len(outputs)} agent/skill files');return 0


if __name__=='__main__':sys.exit(main())
